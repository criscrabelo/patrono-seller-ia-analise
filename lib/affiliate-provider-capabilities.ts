/**
 * AffiliateProviderCapability — o que cada provider PERMITE de verdade,
 * separado do catálogo básico (`lib/affiliate-providers.ts`).
 *
 * Por que uma estrutura separada em vez de só ampliar `AffiliateProvider`:
 * capacidade é uma leitura de política/API que muda com frequência e
 * precisa de reverificação periódica, independente do metadado básico do
 * provider (nome, categoria, URL). Separar os dois deixa claro qual parte
 * é "cadastro" (estável) e qual é "o que a automação pode fazer agora"
 * (instável, precisa de `lastVerifiedAt`).
 *
 * REGRA INEGOCIÁVEL: nenhuma capability aqui foi confirmada contra uma
 * chamada de API ao vivo — este ambiente de desenvolvimento não tem acesso
 * à internet externa. Os campos vêm de conhecimento geral sobre políticas
 * de plataforma amplamente estáveis (ex.: "scraping não é uma fonte
 * autorizada em nenhuma dessas plataformas", "TikTok e Instagram exigem
 * API oficial para publicar") — não de uma consulta em tempo real à
 * documentação de cada provider. Por isso `sourceType` nunca é
 * `OFFICIAL_API` aqui (nenhuma chamada foi feita) e `confidence` nunca é
 * `HIGH` para um detalhe específico (limite exato, nome de endpoint,
 * percentual de comissão) — só para uma regra de política muito estável e
 * amplamente documentada. Qualquer coisa mais específica é `NOT_VERIFIED`.
 * Antes de qualquer automação real usar isto, reverificar contra a fonte
 * oficial e atualizar `lastVerifiedAt`.
 *
 * A UI e a automação devem sempre CONSULTAR estes campos — nunca hardcodar
 * "a Shopee permite X" em um componente. Ver REGRAS-PROVIDERS-E-CANAIS.md
 * para a versão em texto corrido, por plataforma.
 */

export type StatusProvider =
  | 'SUPPORTED_MANUAL' // funciona hoje, só manualmente (o padrão do MVP)
  | 'OFFICIAL_API_AVAILABLE' // existe API oficial pública para pelo menos parte do fluxo
  | 'AUTHORIZATION_REQUIRED' // API existe, mas exige aprovação/credencial que não temos ainda
  | 'PARTNER_ACCESS_REQUIRED' // só acessível via parceria/rede intermediária (ex.: rede de afiliação)
  | 'NOT_VERIFIED' // não conferimos contra fonte oficial ainda
  | 'NOT_AVAILABLE' // não há caminho oficial conhecido
  | 'BLOCKED_BY_POLICY' // a plataforma proíbe explicitamente automação nesse ponto

export type SourceType =
  | 'OFFICIAL_DOCS' // documentação oficial da plataforma, lida por uma pessoa/Claude, sem chamada de API
  | 'OFFICIAL_API' // resposta real de uma chamada à API oficial (ninguém aqui ainda)
  | 'AUTHORIZED_PARTNER_DOCS' // documentação de uma rede/parceiro autorizado (Awin, Rakuten etc.)
  | 'NOT_VERIFIED'

export type ConfidenceLevel = 'HIGH' | 'MEDIUM' | 'LOW' | 'UNKNOWN'

export interface AffiliateProviderCapability {
  providerId: string
  country: string
  affiliateProgramAvailable: boolean
  productCatalogAccess: boolean
  bestSellerData: boolean
  trendData: boolean
  commissionData: boolean
  affiliateLinkGeneration: 'link-manual' | 'api-oficial' | 'rede-terceira' | 'NOT_VERIFIED'
  salesImport: boolean
  commissionImport: boolean
  webhook: boolean
  officialApi: boolean
  authorizedImport: boolean
  automatedDiscovery: boolean
  automatedPublishing: boolean
  requiresUserConsent: boolean
  // NUNCA true. Não existe provider nesta plataforma onde raspar página é
  // uma fonte autorizada — se isso um dia mudar, precisa de decisão
  // humana explícita, não um "true" solto num array de dados.
  scrapingAllowed: false
  commercialContentRules: string
  lastVerifiedAt: string
  sourceType: SourceType
  status: StatusProvider
  confidence: ConfidenceLevel
  observacao?: string
}

